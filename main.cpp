#include "configreader.h"
#include "log.h"
#include "mainwindow.h"

#include <QApplication>
#include <QFontDatabase>

#include <cstdlib>
#include <filesystem>
#include <format>
#include <iostream>

int main(int argc, char* argv[])
{
    try {
        std::filesystem::path exe(argv[0]);
        std::filesystem::path cwd = exe.remove_filename();
        cwd = std::filesystem::canonical(cwd);

        // Locate our resources (default values for e.g. Linux)
        std::string dataDir = (cwd / "data").string();
        std::string configDir = cwd.string();
        std::string logDir = cwd.string();
#ifdef __APPLE__
        // If on MacOS, this app is designed to work inside a "bundle", i.e.
        // level_designer.app/
        // └── Contents/
        //     ├── Info.plist          ← generated by CMake
        //     ├── MacOS/
        //     │   └── level_designer  ← the binary
        //     ├── Frameworks/         ← bundled Qt etc (release builds only)
        //     ├── PlugIns/            ← bundled Qt plugins (release builds only)
        //     └── Resources/
        //         ├── ld.icns             ← app icon
        //         ├── level_designer.cfg  ← runtime config
        //         └── data/               ← runtime data
        if (std::filesystem::exists(cwd.parent_path() / "Resources")) {
            dataDir = (cwd.parent_path() / "Resources/data").string();
            configDir = (cwd.parent_path() / "Resources").string();
        }
        const char* home = getenv("HOME");
        logDir = std::string(home) + "/Library/Logs/level_designer";
        std::filesystem::create_directories(logDir);
#endif
        mgo::ConfigReader config(std::format("{}/level_designer.cfg", configDir));
        mgo::Log::init(std::format("{}/level_designer.log", logDir));
        mgo::Log::info("Starting level_designer");
        mgo::Log::debug("Data Dir = {}", dataDir);

        QApplication app(argc, argv);
        // These determine where settings are saved
        QCoreApplication::setOrganizationName("marengo");
        QCoreApplication::setApplicationName("level_designer");

        // Font used for text drawn on the level (e.g. "EXIT")
        QString fontFamily;
        const int fontId = QFontDatabase::addApplicationFont(
            QString::fromStdString(std::format("{}/DroidSansMono.ttf", dataDir)));
        if (fontId >= 0) {
            fontFamily = QFontDatabase::applicationFontFamilies(fontId).value(0);
        } else {
            mgo::Log::warn("Could not load font from {}", dataDir);
        }

        const int width = static_cast<int>(config.readLong("WindowWidth", 1200));
        const int height = static_cast<int>(config.readLong("WindowHeight", 900));
        mgo::MainWindow window(width, height, fontFamily);

        // An optional level file to open. If it doesn't exist, it's created on save.
        const QStringList args = QCoreApplication::arguments();
        if (args.size() > 1) {
            window.loadFile(args[1]);
        }

        if (config.readBool("FullScreen", false)) {
            window.showFullScreen();
        } else {
            window.show();
        }
        return app.exec();
    } catch (const std::exception& e) {
        // anything caught here is a terminal event
        std::cout << e.what() << std::endl;
    }
    return 1;
}
