#include "configreader.h"
#include "imgui_dialog.h"
#include "level.h"
#include "log.h"

#include <SFML/Graphics.hpp>
#include <imgui-SFML.h>
#include <iostream>

int main(int, char* argv[])
{
    try {

        std::filesystem::path exe(argv[0]);
        std::filesystem::path cwd = exe.remove_filename();
        cwd = std::filesystem::canonical(cwd);

        // Locate our resources (default values for e.g. Linux)
        std::string dataDir = (cwd / "data/").string();
        std::string configDir = cwd.string();
        std::string logDir = cwd.string();
#ifdef __APPLE__
        // If on MacOS, this app is designed to work inside a "bundle", i.e.
        // amaze.app/
        // └── Contents/
        //     ├── Info.plist          ← generated by CMake
        //     ├── MacOS/
        //     │   └── amaze           ← the binary
        //     ├── Frameworks/
        //     │   └── *.dylib         ← bundled dylibs (copied by dylibbundler)
        //     └── Resources/
        //         ├── amaze.icns      ← app icon
        //         ├── amaze.cfg       ← runtime config
        //         └── data/           ← runtime data
        if (std::filesystem::exists(cwd.parent_path() / "Resources")) {
            dataDir = (cwd.parent_path() / "Resources/data/").string();
            configDir = (cwd.parent_path() / "Resources").string();
        }
        const char* home = getenv("HOME");
        logDir = std::string(home) + "/Library/Logs/amaze";
        std::filesystem::create_directories(logDir);
#endif
        mgo::ConfigReader config(std::format("{}/level_designer.cfg", configDir));
        mgo::Log::init(std::format("{}/level_designer.log", logDir));
        mgo::Log::info("Starting level_designer");
        mgo::Log::debug("Data Dir = {}", dataDir.c_str());

        std::string loadFileName { "/Users/mcd/tmp/new3.lvl" }; // TODO implement loading
        // TODO conditional macos bundle paths
        // TODO if (argc != 2) {
        // TODO     std::cout << "Usage: level_designer <filename>\n\n";
        // TODO     std::cout << "If the file doesn't exist it will be created on save\n\n";
        // TODO     return 1;
        // TODO }

        unsigned screenWidth = static_cast<unsigned>(config.readLong("WindowWidth", 800));
        unsigned screenHeight = static_cast<unsigned>(config.readLong("WindowHeight", 800));
        const bool fullscreen = config.readBool("Fullscreen", false);
        const auto mode = sf::VideoMode::getDesktopMode();
        if (fullscreen) {
            // If fullscreen, we use the desktop resolution
            screenWidth = mode.size.x;
            screenHeight = mode.size.y;
        }
        sf::RenderWindow window(
            fullscreen ? mode : sf::VideoMode({ screenWidth, screenHeight }),
            loadFileName,
            sf::Style::Titlebar | sf::Style::Close,
            fullscreen ? sf::State::Fullscreen : sf::State::Windowed);
        window.setFramerateLimit(24);

        mgo::Level level(window, screenWidth, screenHeight, dataDir.c_str());
        mgo::imgui::Dialog dialog(window, dataDir.c_str());

        level.load(loadFileName);
        mgo::imgui::Status menuStatus;

        while (window.isOpen()) {
            for (;;) {
                // imgui polls for events, processEvents() returns us
                // a set of events that it didn't handle
                auto unprocessedEvents = dialog.processEvents();
                for (const auto& e : unprocessedEvents) {
                    level.processEvent(window, e);
                }
                level.processMenuInput(menuStatus);

                level.clampViewport();
                // Draw the floating view items:
                // Note that .setView() changes whether we're writing to the
                // scrolling or fixed "canvas".
                window.setView(level.getView());
                window.clear();
                level.drawGridLines(window);
                level.draw(window);
                level.drawObjects(window);
                // Draw items to the FIXED view:
                // See note above re .setView()
                window.setView(level.getFixedView());
                level.drawModes(window);
                level.drawDialog(window);
                menuStatus = dialog.build();
                if (menuStatus.quit) {
                    window.close();
                    break;
                }
                dialog.render();
                // Set view back otherwise mouse coords appear to be
                // reported in the wrong position
                window.setView(level.getView());
                window.display();
            }
        }
        return 0;
    } catch (const std::exception& e) {
        // anything caught here is a terminal event
        std::cout << e.what() << std::endl;
    }
    return 1;
}
